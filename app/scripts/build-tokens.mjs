// Generates src/styles/tokens.css (Tailwind v4 @theme) from replica/design/tokens.json.
// Run: npm run tokens   (also runs before dev and build)
// The default Tailwind palette, fonts, radii, shadows and text sizes are cleared, so components
// can only use the project's tokens (bg-surface, text-muted, rounded-md, shadow-pop, text-sm...).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, "../../replica/design/tokens.json");
const TARGET = resolve(here, "../src/styles/tokens.css");

const HEX = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i;
const NAME = /^[a-z0-9-]+$/;

function fail(message) {
  console.error(`build-tokens: ${message}`);
  process.exit(1);
}

function readTokens() {
  try {
    return JSON.parse(readFileSync(SOURCE, "utf8"));
  } catch (error) {
    fail(`cannot read ${SOURCE}: ${error.message}`);
  }
}

function checkName(group, name) {
  if (!NAME.test(name)) fail(`${group}.${name}: names must be lowercase letters, digits and dashes`);
}

function colorLines(colors) {
  return Object.entries(colors).map(([name, value]) => {
    checkName("color", name);
    if (!HEX.test(value)) fail(`color.${name}: ${value} is not a hex colour`);
    return `  --color-${name}: ${value};`;
  });
}

function typeLines(type) {
  return Object.entries(type).flatMap(([name, t]) => {
    checkName("type", name);
    if (![t.size, t.line, t.weight].every(Number.isFinite)) fail(`type.${name}: size, line, weight must be numbers`);
    return [
      `  --text-${name}: ${t.size / 16}rem;`,
      `  --text-${name}--line-height: ${t.line / 16}rem;`,
      `  --text-${name}--font-weight: ${t.weight};`,
    ];
  });
}

function pxLines(prefix, group, values) {
  return Object.entries(values).map(([name, value]) => {
    checkName(group, name);
    if (!Number.isFinite(value)) fail(`${group}.${name}: must be a number`);
    return `  --${prefix}-${name}: ${value === 999 ? "9999px" : `${value / 16}rem`};`;
  });
}

function rawLines(prefix, group, values) {
  return Object.entries(values).map(([name, value]) => {
    checkName(group, name);
    return `  --${prefix}-${name}: ${value};`;
  });
}

function layoutLines(layout) {
  return Object.entries(layout)
    .filter(([, value]) => Number.isFinite(value))
    .map(([name, value]) => `  --layout-${name}: ${value / 16}rem;`);
}

function build(tokens) {
  const { color, type, radius, shadow, font, motion, layout, space } = tokens;
  if (!color || !type || !radius || !shadow || !font || !motion || !layout) {
    fail("tokens.json needs color, type, radius, shadow, font, motion and layout");
  }
  if (!Array.isArray(space) || space.some((step) => step % 4 !== 0)) {
    fail("space must be a list on a 4px base (Tailwind's default --spacing of 0.25rem is kept)");
  }

  const theme = [
    "  --color-*: initial;",
    "  --color-transparent: transparent;",
    "  --color-current: currentColor;",
    ...colorLines(color),
    "",
    "  --font-*: initial;",
    ...rawLines("font", "font", font),
    "",
    "  --text-*: initial;",
    ...typeLines(type),
    "",
    "  --radius-*: initial;",
    ...pxLines("radius", "radius", radius),
    "",
    "  --shadow-*: initial;",
    ...rawLines("shadow", "shadow", shadow),
    "",
    `  --ease-standard: ${motion.ease};`,
    "  --spacing: 0.25rem;",
  ];

  const root = [
    `  --duration-fast: ${motion.fast};`,
    `  --duration-base: ${motion.base};`,
    ...layoutLines(layout),
  ];

  return [
    "/* GENERATED by scripts/build-tokens.mjs from replica/design/tokens.json. Do not edit by hand. */",
    "@theme {",
    ...theme,
    "}",
    "",
    ":root {",
    ...root,
    "}",
    "",
  ].join("\n");
}

const css = build(readTokens());
mkdirSync(dirname(TARGET), { recursive: true });
writeFileSync(TARGET, css);
console.log(`build-tokens: wrote ${TARGET}`);
